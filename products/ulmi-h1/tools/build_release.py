#!/usr/bin/env python3
"""Build and verify a reproducible, source-only ULMi H1 technical ZIP.

Product acceptance, genuine Qwen and owner UAT are separate. The source tree is
read-only here; symlinks inside included paths fail closed, and generated bytecode
cannot change the delivery hash.
"""
from __future__ import annotations
import hashlib
import io
import json
import os
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INCLUDE = (
    'PRODUCT/', 'TESTS/',
    'ORIGINALS/V22_IMMUTABLE_SOURCE.json',
    'ORIGINALS/PILOT_ABC_IMMUTABLE_SOURCE.json',
    'RESEARCH_ARCHIVE/canonical_sources/',
    'FROZEN_HANDOFF/V22_12_EXACT_ACCEPTANCE_LEDGER.json',
    'EVIDENCE/OWNER_V5_SAFARI_UAT_RAW.json',
    'START_H1.sh', 'README_H1_EMIR01_R2.md', 'README_GITHUB_H1.md',
    'tools/',
)
EXCLUDE_COMPONENTS = {'__pycache__', '.pytest_cache', '.mypy_cache', '.ruff_cache', '.DS_Store'}
EXCLUDE_EXTENSIONS = {'.pyc', '.pyo', '.swp', '.tmp'}
ZIP_PREFIX = 'ULMI_H1/'
MANIFEST_NAME = ZIP_PREFIX + 'RELEASE_MANIFEST.json'


def selected(rel: str) -> bool:
    return any(rel == entry or (entry.endswith('/') and rel.startswith(entry)) for entry in INCLUDE)


def generated(rel: str) -> bool:
    parts = Path(rel).parts
    return any(p in EXCLUDE_COMPONENTS for p in parts) or Path(rel).suffix in EXCLUDE_EXTENSIONS


def collect(root: Path = ROOT):
    """Return sorted immutable source bytes; reject all included symlink paths."""
    records = []
    for path in sorted(root.rglob('*')):
        rel = path.relative_to(root).as_posix()
        if not selected(rel) or generated(rel):
            continue
        if path.is_symlink():
            raise ValueError('HOLD_RELEASE_SYMLINK:' + rel)
        if path.is_dir():
            continue
        if not path.is_file():
            raise ValueError('HOLD_RELEASE_NONREGULAR:' + rel)
        content = path.read_bytes()
        records.append((rel, content))
    if not records:
        raise ValueError('HOLD_EMPTY_RELEASE')
    return records


def manifest_bytes(records):
    data = {
        'schema': 'enguru.ulmi-h1.source-release-manifest/v1',
        'authority': 'TECHNICAL_CANDIDATE_NOT_OWNER_APPROVAL',
        'h2': 'PARKED',
        'files': [
            {'path': rel, 'sha256': hashlib.sha256(content).hexdigest(), 'size_bytes': len(content)}
            for rel, content in records
        ],
    }
    return (json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(',', ':')) + '\n').encode('utf-8')


def make(root: Path = ROOT):
    records = collect(root)
    manifest = manifest_bytes(records)
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for rel, content in [*records, ('RELEASE_MANIFEST.json', manifest)]:
            info = zipfile.ZipInfo(ZIP_PREFIX + rel, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, content, compress_type=zipfile.ZIP_DEFLATED, compresslevel=9)
    return buffer.getvalue(), records, manifest


def verify(blob: bytes):
    """Verify exact manifest membership, content hashes and explicit source-only scope."""
    with zipfile.ZipFile(io.BytesIO(blob)) as archive:
        if archive.testzip() is not None:
            raise ValueError('HOLD_RELEASE_ZIP_CRC')
        members = archive.namelist()
        if len(members) != len(set(members)) or members.count(MANIFEST_NAME) != 1:
            raise ValueError('HOLD_RELEASE_MEMBERS')
        manifest = json.loads(archive.read(MANIFEST_NAME))
        assert manifest['schema'] == 'enguru.ulmi-h1.source-release-manifest/v1'
        expected = {ZIP_PREFIX + row['path']: row for row in manifest['files']}
        if set(members) != set(expected) | {MANIFEST_NAME}:
            raise ValueError('HOLD_RELEASE_MEMBER_DRIFT')
        for name, row in expected.items():
            if generated(row['path']) or not selected(row['path']):
                raise ValueError('HOLD_RELEASE_UNSELECTED:' + row['path'])
            data = archive.read(name)
            if len(data) != row['size_bytes'] or hashlib.sha256(data).hexdigest() != row['sha256']:
                raise ValueError('HOLD_RELEASE_SHA_DRIFT:' + name)
        return manifest


def main(args):
    first, records, manifest = make()
    second, _, _ = make()
    if first != second:
        raise ValueError('HOLD_RELEASE_NONDETERMINISTIC')
    checked = verify(first)
    target = Path(args[1] if len(args) > 1 else '/tmp/ulmi-h1-technical-candidate.zip')
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(first)
    receipt = {
        'state': 'PASS_SCOPED_SOURCE_ONLY_DETERMINISTIC_ARTIFACT',
        'source_file_count': len(records),
        'manifest_sha256': hashlib.sha256(manifest).hexdigest(),
        'zip_sha256': hashlib.sha256(first).hexdigest(),
        'size_bytes': len(first),
        'two_builds_byte_equal': True,
        'manifest_entries_verified': len(checked['files']),
        'pycache_excluded': True,
        'included_symlinks_rejected': True,
        'source_git_commit': os.environ.get('GITHUB_SHA', 'NOT_BOUND_TO_GITHUB_RUNNER'),
        'original_formal_12': 'HOLD',
        'actual_qwen': 'NOT_TESTED',
        'browser_uat': 'SEPARATE',
        'owner_final': 'NOT_ISSUED',
    }
    receipt_path = target.with_suffix('.receipt.json')
    receipt_path.write_text(json.dumps(receipt, ensure_ascii=False, sort_keys=True, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(receipt, ensure_ascii=False, sort_keys=True))
    return receipt


if __name__ == '__main__':
    main(sys.argv)
